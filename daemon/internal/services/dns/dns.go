package dns

import (
	"context"
	"fmt"
	"os/exec"
	"strings"

	"github.com/opencr/ocrd/internal/config"
	"go.uber.org/zap"
)

// Service wraps Unbound DNS resolver
type Service struct {
	cfg    config.DNSConfig
	logger *zap.Logger
	cmd    *exec.Cmd
}

// NewService creates a new DNS service
func NewService(cfg config.DNSConfig, logger *zap.Logger) *Service {
	return &Service{cfg: cfg, logger: logger}
}

// Start starts Unbound DNS resolver
func (s *Service) Start(ctx context.Context) error {
	if !s.cfg.Enabled {
		return nil
	}

	path, err := exec.LookPath("unbound")
	if err != nil {
		s.logger.Warn("unbound not found, DNS service disabled")
		return fmt.Errorf("unbound not found: %w", err)
	}

	s.logger.Info("starting Unbound DNS", zap.String("path", path))
	s.cmd = exec.CommandContext(ctx, path, "-c", "/etc/unbound/unbound.conf", "-d")

	if err := s.cmd.Start(); err != nil {
		return fmt.Errorf("start unbound: %w", err)
	}

	go func() {
		if err := s.cmd.Wait(); err != nil {
			s.logger.Warn("unbound exited", zap.Error(err))
		}
	}()

	return nil
}

// Stop stops the DNS service
func (s *Service) Stop() {
	if s.cmd != nil && s.cmd.Process != nil {
		s.cmd.Process.Kill() //nolint:errcheck
	}
}

// GetConfig returns the current DNS configuration
func (s *Service) GetConfig() map[string]interface{} {
	return map[string]interface{}{
		"enabled":    s.cfg.Enabled,
		"listen":     s.cfg.ListenAddr,
		"forwarders": s.cfg.Forwarders,
		"zones":      s.cfg.LocalZones,
	}
}

// GenerateConfig generates unbound.conf from config
func (s *Service) GenerateConfig() string {
	var b strings.Builder

	b.WriteString("# Generated by OCR daemon\n\n")
	b.WriteString("server:\n")
	b.WriteString(fmt.Sprintf("  interface: %s\n", s.cfg.ListenAddr))
	b.WriteString("  do-ip4: yes\n")
	b.WriteString("  do-ip6: yes\n")
	b.WriteString("  do-udp: yes\n")
	b.WriteString("  do-tcp: yes\n")
	b.WriteString("  access-control: 127.0.0.0/8 allow\n")
	b.WriteString("  access-control: 10.0.0.0/8 allow\n")
	b.WriteString("  access-control: 172.16.0.0/12 allow\n")
	b.WriteString("  access-control: 192.168.0.0/16 allow\n")
	b.WriteString("  cache-min-ttl: 60\n")
	b.WriteString("  cache-max-ttl: 86400\n")
	b.WriteString("  prefetch: yes\n")
	b.WriteString("  hide-identity: yes\n")
	b.WriteString("  hide-version: yes\n\n")

	if len(s.cfg.Forwarders) > 0 {
		b.WriteString("forward-zone:\n")
		b.WriteString("  name: \".\"\n")
		for _, fwd := range s.cfg.Forwarders {
			b.WriteString(fmt.Sprintf("  forward-addr: %s\n", fwd))
		}
	}

	return b.String()
}
