package dhcp

import (
	"context"
	"fmt"
	"net"
	"os/exec"
	"sync"
	"time"

	"github.com/opencr/ocrd/internal/config"
	"go.uber.org/zap"
)

// Lease represents a DHCP lease
type Lease struct {
	MAC      string    `json:"mac"`
	IP       string    `json:"ip"`
	Hostname string    `json:"hostname"`
	Expires  time.Time `json:"expires"`
}

// Service wraps a DHCP server (ISC dhcpd or kea-dhcp4)
type Service struct {
	cfg    config.DHCPConfig
	logger *zap.Logger
	mu     sync.RWMutex
	leases []*Lease
	cmd    *exec.Cmd
}

// NewService creates a new DHCP service
func NewService(cfg config.DHCPConfig, logger *zap.Logger) *Service {
	return &Service{cfg: cfg, logger: logger}
}

// Start starts the DHCP server
func (s *Service) Start(ctx context.Context) error {
	if !s.cfg.Enabled {
		return nil
	}

	// Try to use kea-dhcp4 or fall back to dhcpd
	if path, err := exec.LookPath("kea-dhcp4"); err == nil {
		s.logger.Info("starting Kea DHCP4", zap.String("path", path))
		s.cmd = exec.CommandContext(ctx, path, "-c", "/etc/kea/kea-dhcp4.conf")
	} else if path, err := exec.LookPath("dhcpd"); err == nil {
		s.logger.Info("starting ISC dhcpd", zap.String("path", path))
		s.cmd = exec.CommandContext(ctx, path, "-f", "-cf", "/etc/dhcp/dhcpd.conf")
	} else {
		s.logger.Warn("no DHCP server found (kea-dhcp4 or dhcpd)")
		return fmt.Errorf("no DHCP server binary found")
	}

	if err := s.cmd.Start(); err != nil {
		return fmt.Errorf("start DHCP server: %w", err)
	}

	go func() {
		if err := s.cmd.Wait(); err != nil {
			s.logger.Warn("DHCP server exited", zap.Error(err))
		}
	}()

	return nil
}

// Stop stops the DHCP server
func (s *Service) Stop() {
	if s.cmd != nil && s.cmd.Process != nil {
		s.cmd.Process.Kill() //nolint:errcheck
	}
}

// GetLeases returns current DHCP leases
func (s *Service) GetLeases() []*Lease {
	s.mu.RLock()
	defer s.mu.RUnlock()

	// In production: parse /var/lib/dhcp/dhcpd.leases or query Kea REST API
	return s.leases
}

// AddLease (internal) adds a new lease record
func (s *Service) AddLease(mac, ip, hostname string, duration time.Duration) {
	s.mu.Lock()
	defer s.mu.Unlock()

	hwAddr, _ := net.ParseMAC(mac)
	_ = hwAddr

	s.leases = append(s.leases, &Lease{
		MAC:      mac,
		IP:       ip,
		Hostname: hostname,
		Expires:  time.Now().Add(duration),
	})
}

// GenerateConfig generates dhcpd.conf from config
func (s *Service) GenerateConfig() string {
	cfg := "# Generated by OCR daemon\n\n"
	cfg += "authoritative;\n\n"

	for _, subnet := range s.cfg.Subnets {
		_, ipNet, err := net.ParseCIDR(subnet.Network)
		if err != nil {
			continue
		}
		mask := net.IP(ipNet.Mask).String()
		cfg += fmt.Sprintf("subnet %s netmask %s {\n", ipNet.IP, mask)
		cfg += fmt.Sprintf("  range %s %s;\n", subnet.RangeStart, subnet.RangeEnd)
		cfg += fmt.Sprintf("  option routers %s;\n", subnet.Gateway)
		if len(subnet.DNS) > 0 {
			dnsStr := ""
			for i, d := range subnet.DNS {
				if i > 0 { dnsStr += ", " }
				dnsStr += d
			}
			cfg += fmt.Sprintf("  option domain-name-servers %s;\n", dnsStr)
		}
		if subnet.LeaseTime > 0 {
			cfg += fmt.Sprintf("  default-lease-time %d;\n", subnet.LeaseTime)
			cfg += fmt.Sprintf("  max-lease-time %d;\n", subnet.LeaseTime*2)
		}
		cfg += "}\n\n"
	}

	return cfg
}
